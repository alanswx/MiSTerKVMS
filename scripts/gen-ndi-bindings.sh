#!/usr/bin/env bash
# Regenerate core/src/ndi/sys.rs from the vendored NDI headers.
# Requires: cargo install bindgen-cli
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
export LIBCLANG_PATH=${LIBCLANG_PATH:-$(xcode-select -p)/Toolchains/XcodeDefault.xctoolchain/usr/lib}
{
  echo "// Generated by scripts/gen-ndi-bindings.sh from third_party/ndi/include ($(head -1 "$ROOT/third_party/ndi/Version.txt" | tr -d '\r')). Do not edit."
  echo "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]"
  bindgen "$ROOT/third_party/ndi/include/Processing.NDI.Lib.h" \
    --allowlist-type 'NDIlib_.*' --allowlist-var 'NDIlib_.*' \
    --allowlist-function 'NDIlib_v6_load' \
    --no-prepend-enum-name --no-layout-tests --use-core \
    -- -x c -std=c99
} > "$ROOT/core/src/ndi/sys.rs"
echo "Wrote core/src/ndi/sys.rs"
